CREATE TABLE `sys_log0` (
  `id` varchar(32) NOT NULL,
  `log_type` int(2) DEFAULT NULL COMMENT 'Loại nhật ký (1 Nhật ký đăng nhập, 2 Nhật ký thao tác)',
  `log_content` varchar(1000) DEFAULT NULL COMMENT 'Nội dung nhật ký',
  `operate_type` int(2) DEFAULT NULL COMMENT 'Loại thao tác',
  `userid` varchar(32) DEFAULT NULL COMMENT 'Tài khoản người dùng thao tác',
  `username` varchar(100) DEFAULT NULL COMMENT 'Tên người dùng thao tác',
  `ip` varchar(100) DEFAULT NULL COMMENT 'IP',
  `method` varchar(500) DEFAULT NULL COMMENT 'Phương thức Java được yêu cầu',
  `request_url` varchar(255) DEFAULT NULL COMMENT 'Đường dẫn yêu cầu',
  `request_param` longtext DEFAULT NULL COMMENT 'Tham số yêu cầu',
  `request_type` varchar(10) DEFAULT NULL COMMENT 'Loại yêu cầu',
  `cost_time` bigint(20) DEFAULT NULL COMMENT 'Thời gian tốn',
  `create_by` varchar(32) DEFAULT NULL COMMENT 'Người tạo',
  `create_time` datetime DEFAULT NULL COMMENT 'Thời gian tạo',
  `update_by` varchar(32) DEFAULT NULL COMMENT 'Người cập nhật',
  `update_time` datetime DEFAULT NULL COMMENT 'Thời gian cập nhật',
  PRIMARY KEY (`id`) USING BTREE,
  KEY `index_table_userid` (`userid`) USING BTREE,
  KEY `index_logt_ype` (`log_type`) USING BTREE,
  KEY `index_operate_type` (`operate_type`) USING BTREE,
  KEY `index_createtime` (`create_time`) USING BTREE
) ENGINE=MyISAM DEFAULT CHARSET=utf8 ROW_FORMAT=DYNAMIC COMMENT='Bảng nhật ký hệ thống';

